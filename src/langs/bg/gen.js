/* Генератор вправ на числа, ціни, час і дати (без DOM — його також використовує validate.mjs).
 * У даних уроку: { t: 'g', g: '<назва>', min?, max? } — під час запуску перетворюється на звичайну вправу 'l' або 'i'. */
(function (BG) {
  'use strict';
  const ONES = ['нула', 'едно', 'две', 'три', 'четири', 'пет', 'шест', 'седем', 'осем', 'девет', 'десет', 'единадесет', 'дванадесет', 'тринадесет',
    'четиринадесет', 'петнадесет', 'шестнадесет', 'седемнадесет', 'осемнадесет', 'деветнадесет'];
  // У розмові 11–19 і десятки скорочують (двайсет, трийсет, шейсет) — учень чутиме саме їх, тож і на письмі вони правильні
  const ONES_C = ONES.slice(0, 11).concat(['единайсет', 'дванайсет', 'тринайсет', 'четиринайсет', 'петнайсет', 'шестнайсет', 'седемнайсет',
    'осемнайсет', 'деветнайсет']);
  const TENS = ['', '', 'двадесет', 'тридесет', 'четиридесет', 'петдесет', 'шестдесет', 'седемдесет', 'осемдесет', 'деветдесет'];
  const TENS_C = ['', '', 'двайсет', 'трийсет', 'четирийсет', 'петдесет', 'шейсет', 'седемдесет', 'осемдесет', 'деветдесет'];
  const HUND = ['', 'сто', 'двеста', 'триста', 'четиристотин', 'петстотин', 'шестстотин', 'седемстотин', 'осемстотин', 'деветстотин'];
  // Дата — порядковий числівник чоловічого роду: «трети май»
  const ORD = ['', 'първи', 'втори', 'трети', 'четвърти', 'пети', 'шести', 'седми', 'осми', 'девети', 'десети', 'единадесети', 'дванадесети',
    'тринадесети', 'четиринадесети', 'петнадесети', 'шестнадесети', 'седемнадесети', 'осемнадесети', 'деветнадесети', 'двадесети'];
  for (let d = 21; d <= 29; d++) ORD[d] = 'двадесет и ' + ORD[d - 20];
  ORD[30] = 'тридесети'; ORD[31] = 'тридесет и първи';
  const MONTH = ['', 'януари', 'февруари', 'март', 'април', 'май', 'юни', 'юли', 'август', 'септември', 'октомври', 'ноември', 'декември'];
  const MONTH_DAYS = [0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];

  /** Число 0–9999 словами. g — рід для 1 і 2 в кінці: 'n' (едно, две — так і лічать), 'm' (един, два), 'f' (една, две);
   *  colloq — розмовні форми (двайсет, петнайсет). Сполучник «и» стоїть перед останньою частиною: сто двадесет и пет, сто и пет */
  function words(n, g, colloq) {
    if (n === 0) return 'нула';
    const O = colloq ? ONES_C : ONES, T = colloq ? TENS_C : TENS;
    const end = (k) => (k === 1 ? (g === 'm' ? 'един' : g === 'f' ? 'една' : 'едно') : k === 2 ? (g === 'm' ? 'два' : 'две') : O[k]);
    const th = Math.floor(n / 1000), h = Math.floor((n % 1000) / 100), r = n % 100;
    const parts = [];
    if (th) parts.push(th === 1 ? 'хиляда' : words(th, 'f', colloq) + ' хиляди');
    if (h) parts.push(HUND[h]);
    if (r && r < 20) parts.push(end(r));
    else if (r) { parts.push(T[Math.floor(r / 10)]); if (r % 10) parts.push(end(r % 10)); }
    if (parts.length > 1) parts.splice(parts.length - 1, 0, 'и');
    return parts.join(' ');
  }
  // Усі правильні записи числа: книжний і розмовний, а для 1 і 2 в кінці — кожен рід
  function allWords(n) {
    const gs = /^(?:\d*[^1])?[12]$/.test(String(n)) ? ['n', 'm', 'f'] : ['n'];
    return Array.from(new Set(gs.flatMap((g) => [words(n, g), words(n, g, true)])));
  }
  // «евро» не змінюється: едно евро, две евро, пет евро
  const euros = (e, colloq) => words(e, 'n', colloq) + ' евро';
  // Після числа іменник чоловічого роду має лічильну форму: два цента, двадесет и пет цента
  const cents = (c, colloq) => words(c, 'm', colloq) + ' цента';
  const rnd = (a, b) => a + Math.floor(Math.random() * (b - a + 1));
  const digits = (s) => String(s).replace(/[^\d]/g, '');
  // Учень чує живу мову, де розмовні форми не рідші за книжні
  const coin = () => Math.random() < 0.4;

  const G = {
    // 🎧 число → цифрами
    numListen(sp) {
      const n = rnd(sp.min ?? 0, sp.max ?? 100), say = words(n, 'n', coin());
      return { t: 'l', h: 'Прослухайте й запишіть цифрами', say, a: String(n), nodia: true, ph: 'цифрами, напр. 47',
        check: (v) => (digits(v) !== '' && Number(digits(v)) === n ? 'ok' : 'bad'), e: 'Словами: ' + words(n) + (say !== words(n) ? ' (розмовно: ' + say + ')' : '') };
    },
    // 🎧 ціна → цифрами
    priceListen(sp) {
      const e = rnd(sp.min ?? 1, sp.max ?? 49);
      // Центи, що закінчуються на 1, звучать по-різному (двадесет и един цента / цент) — щоб не вчити спірного, їх немає
      let c = Math.random() < 0.25 ? 0 : rnd(10, 99);
      if (c % 10 === 1) c += 1;
      const col = coin(), say = euros(e, col) + (c ? ' и ' + cents(c, col) : '');
      const shown = e + ',' + String(c).padStart(2, '0') + ' €';
      return { t: 'l', h: 'Прослухайте ціну й запишіть цифрами', say, a: shown, nodia: true, ph: 'напр. 3,49',
        check: (v) => {
          const m = String(v).replace(/€|евро|eur/gi, '').replace(/\s+/g, '').replace(',-', '').replace(',', '.');
          return m !== '' && !isNaN(+m) && Math.round(+m * 100) === e * 100 + c ? 'ok' : 'bad';
        }, e: 'Словами: ' + say };
    },
    // 🎧 «в колко часа» → цифрами
    timeListen() {
      // «един часа» і «двадесет и един часа» звучать незграбно — о першій і двадцять першій кажуть із хвилинами
      const h = rnd(1, 23), m = h === 1 || h === 21 ? rnd(1, 11) * 5 : Math.random() < 0.4 ? 0 : rnd(1, 11) * 5;
      const col = coin(), say = 'в ' + words(h, 'm', col) + (m ? ' и ' + words(m, 'f', col) : ' часа');
      const shown = h + ':' + String(m).padStart(2, '0');
      return { t: 'l', h: 'Прослухайте час і запишіть цифрами', say, a: shown, nodia: true, ph: 'напр. 14:30',
        check: (v) => {
          // Кома — бо на телефоні цифрова клавіатура (inputmode="decimal") в українській і болгарській локалі має кому, а не двокрапку
          const p = String(v).trim().match(/^(\d{1,2})(?:\s*[:.,\s]\s*(\d{2}))?$/);
          if (!p) return 'bad';
          const hh = +p[1], mm = p[2] ? +p[2] : 0;
          return mm === m && (hh === h || (h <= 12 && hh === h + 12) || (h > 12 && hh === h - 12)) ? 'ok' : 'bad';
        }, e: 'Словами: ' + say + (h <= 12 ? ' (можна і ' + (h + 12) + ':' + String(m).padStart(2, '0') + ')' : '') };
    },
    // 🎧 дата → цифрами
    dateListen() {
      const mo = rnd(1, 12), d = rnd(1, MONTH_DAYS[mo]);
      const say = ORD[d] + ' ' + MONTH[mo];
      return { t: 'l', h: 'Прослухайте дату й запишіть цифрами (день. місяць.)', say, a: d + '. ' + mo + '.', nodia: true, ph: 'напр. 24. 8.',
        check: (v) => { const p = String(v).match(/(\d{1,2})\D+(\d{1,2})/); return p && +p[1] === d && +p[2] === mo ? 'ok' : 'bad'; },
        e: 'Словами: ' + say };
    },
    // ✍️ число → словами
    numWords(sp) {
      const n = rnd(sp.min ?? 0, sp.max ?? 100), a = allWords(n);
      return { t: 'i', q: 'Напишіть словами число <b>' + n + '</b>', a, nospace: true, say: words(n),
        e: '[[' + words(n) + ']]' + (a.length > 1 ? ' — інші правильні форми: ' + a.slice(1).join(', ') : '') + '. «и» — перед останньою частиною числа.' };
    },
    // ✍️ час → словами
    timeWords() {
      const h = rnd(2, 11), m = [0, 15, 30, 45][rnd(0, 3)];
      const H = (x, col) => words(x, 'm', col);
      let ans;
      if (m === 0) ans = [H(h) + ' часа', H(h), H(h, true) + ' часа'];
      else if (m === 15) ans = [H(h) + ' и петнадесет', H(h) + ' и петнайсет', H(h) + ' и четвърт'];
      else if (m === 30) ans = [H(h) + ' и половина', H(h) + ' и тридесет', H(h) + ' и трийсет'];
      else ans = [H(h + 1) + ' без петнадесет', H(h + 1) + ' без петнайсет', H(h + 1) + ' без четвърт', H(h) + ' и четиридесет и пет', H(h) + ' и четирийсет и пет'];
      ans = ans.flatMap((x) => [x, 'в ' + x]);
      return { t: 'i', q: 'О котрій? Напишіть словами: <b>' + h + ':' + String(m).padStart(2, '0') + '</b>', a: ans, nospace: true,
        e: '[[в ' + ans[0] + ']]' + (m === 45 ? ' — «без четвърт»: за чверть наступна година' : '') };
    },
    // ✍️ дата → словами
    dateWords() {
      const mo = rnd(1, 12), d = rnd(1, MONTH_DAYS[mo]);
      const ans = ORD[d] + ' ' + MONTH[mo];
      return { t: 'i', q: 'Напишіть дату словами: <b>' + d + '. ' + mo + '.</b>', a: [ans, 'на ' + ans], nospace: true,
        e: '[[' + ans + ']] — порядковий числівник чоловічого роду + місяць, без змін у відмінках' };
    }
  };

  BG.gen = {
    words, allWords, euros, cents, ORD, MONTH, list: G,
    make(spec) {
      const f = G[spec.g];
      if (!f) throw new Error('Невідомий генератор вправ: ' + spec.g);
      return f(spec);
    }
  };
})(PG.pack('bg'));
