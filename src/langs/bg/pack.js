  // Болгарська пишеться кирилицею, тож український текст у [[ ]] і відповідях validate.mjs упізнає лише за літерами,
  // яких у болгарській немає. Латинська літера посеред болгарського слова — підміна схожої (a / а, e / е, o / о, p / р, c / с),
  // яку голос прочитає неправильно, а перевірка відповіді не зарахує
  BG.foreign = /[a-zіїєґёыэ]/i;
  // [слів від, до, вправ від, до, диктантів від]. A1.13 — урок-повторення без нових слів; диктантів в A1 від одного,
  // бо на слух болгарську тренує ще й тренажер чисел
  BG.limits = { a0: [10, 25, 10, 16, 2], a1: [0, 30, 10, 20, 1] };
  // Літери ъ немає на українській розкладці; ѝ («їй») на письмі відрізняє займенник від сполучника и
  BG.keyboard = ['ъ', 'ѝ'];

  // Наголос у підручниках позначають знаком над голосною (вода́) — у відповіді його не вимагаємо.
  // exact — для вправ саме на ѝ / и: тоді гравіс зберігається
  const norm = (s, exact) => String(s).toLowerCase().normalize('NFD').replace(exact ? /́/g : /[̀́]/g, '').normalize('NFC')
    .replace(/[.,!?;:"„“”'’«»()…–—-]/g, ' ').replace(/\s+/g, ' ').trim();
  // Без болгарської розкладки замість ъ набирають ь або а; з української чи російської звички — і, є, ы, э.
  // Слово впізнається, тож це «майже», а не помилка
  const fold = (s) => s.replace(/[ьа]/g, 'ъ').replace(/[іы]/g, 'и').replace(/[єэ]/g, 'е');
  BG.check = function (input, answers, exact) {
    const list = (Array.isArray(answers) ? answers : [answers]).map((a) => norm(a, exact));
    const n = norm(input, exact);
    if (!n) return 'bad';
    if (list.includes(n)) return 'ok';
    if (!exact && list.some((a) => fold(a) === fold(n) || PG.nearTypo(a, n))) return 'near';
    return 'bad';
  };

