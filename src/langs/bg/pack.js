      '<li><b>Mac / iPhone / iPad</b>: Параметри → Універсальний доступ → Усний вміст → Голоси → Болгарська → завантажити голос. Потім перезапустіть браузер.</li>',
    dictPromo: 'Почули нове слово в магазині, на роботі чи на пляжі? Додайте його в словник — воно потрапить у повторення, а словник можна експортувати й перенести на інший пристрій.',
