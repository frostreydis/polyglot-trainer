    dictWordPh: 'напр. касова бележка',
    dictUkPh: 'напр. чек',
    dictNotePh: 'Примітка: рід (м / ж / ср), наголос, розмовне…',
    dictExPh: 'Приклад: Може ли касова бележка?',
    dictImportPh: 'касова бележка — чек\nлична карта - посвідчення особи\nколичка; візок у магазині\n(можна вставити клітинки з Excel чи Google Таблиць: болгарське слово і переклад у сусідніх колонках)',
    drillTitle: '🔢 Тренажер чисел, цін, часу й дат',
    drillIntro: 'Вправи щоразу нові, по 10 за підхід. На слух — записуєте цифрами, «словами» — пишете болгарською: приймаються і книжні, і розмовні форми (двадесет / двайсет), пробіли не важливі. Почніть із «Числа 0–20» і «Ціни».',
