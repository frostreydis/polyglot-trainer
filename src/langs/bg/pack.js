/* Мовний пакет «Болгарська»: перевірка відповідей кирилицею (без наголосів, ъ замість ь / а — «майже»), клавіатура ъ і ѝ,
 * голос, тексти інтерфейсу, тренажер чисел, цін в євро, часу й дат, довідка про іспит і документи */
